/** Slug से original article ढूंढो। */
export function getOriginalArticle(slug: string): OriginalArticle | undefined {
  return ORIGINAL_ARTICLES.find((a) => a.slug === slug);
}

/** Full article body — plain text (meta description, JSON-LD के लिए)। */
export function articleFullText(a: OriginalArticle): string {
  return a.sections
    .map((s) => (s.heading ? `${s.heading}. ` : "") + s.paragraphs.join(" "))
    .join(" ");
}
